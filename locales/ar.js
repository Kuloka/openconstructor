function pluralAr(n, one, two, few, many) {
  const num = Math.abs(parseInt(n, 10));
  const mod100 = num % 100;
  if (num === 1) return `${n} ${one}`;
  if (num === 2) return `${n} ${two}`;
  if (mod100 >= 3 && mod100 <= 10) return `${n} ${few}`;
  if (mod100 >= 11 && mod100 <= 99) return `${n} ${many}`;
  return `${n} ${one}`;
}

